export function phaseAt(hour) {
  const h = ((hour % 24) + 24) % 24;
  for (const p of SCHEDULE) {
    if (p.from > p.to ? h >= p.from || h < p.to : h >= p.from && h < p.to) return p;
  }
  return SCHEDULE[0];
}

